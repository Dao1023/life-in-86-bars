# 智库估算：育娲人口《中国生育成本报告2022版》，2019 年价格，全国
YUWA = [
    ('0-2岁', 21559, '养育成本=当年全国居民人均消费支出21559元（直接假设）'),
    ('3-5岁', 33559, '人均消费支出+幼儿园/学前教育12000元/年'),
    ('6-14岁', 24072, '人均消费支出+额外一份教育文化娱乐2513元/年'),
    ('15-17岁', 26072, '6-14岁基础上+住校等2000元/年'),
    ('18-21岁', 35500, '大学：学费1万+住宿1500+生活费2.4万'),
]

rows = []
for ev, sid, sname, year, geo, samp, vals, total in BLOCKS:
    assert sum(vals) == total, (sid, sum(vals), total)
    rows.append([ev, sid, sname, year, geo, samp, '全年龄(未分组)', '', '合计', total, '100.00', '元/人/年'])
    for c, v in zip(CATS, vals):
        rows.append([ev, sid, sname, year, geo, samp, '全年龄(未分组)', '', c, v,
                     '%.2f' % (v * 100.0 / total), '元/人/年'])

for band, v, note in YUWA:
    stage = {'0-2岁': '育儿-婴幼儿', '3-5岁': '育儿-学前', '6-14岁': '育儿-义务教育',
             '15-17岁': '育儿-高中', '18-21岁': '育儿-大学'}[band]
    rows.append(['B 研究估算', 'YUWA-2022', '育娲人口《中国生育成本报告2022版》表1/正文', 2019,
                 '全国', '全体居民（按人均消费支出外推）', band, stage, '养育成本合计', v, '',
                 '元/孩子/年；非八大类拆分'])

# 育娲 0-17 岁合计（非年度）
for geo, samp, v in [('全国', '全体居民', 485218), ('城镇', '城镇居民', 630783), ('农村', '农村居民', 299865)]:
    rows.append(['B 研究估算', 'YUWA-2022', '育娲人口《中国生育成本报告2022版》表1/表3', 2019,
                 geo, samp, '0-17岁', '育儿-累计', '养育成本合计', v, '',
                 '元/孩子（0-17岁累计）；非年度值'])

os.makedirs('../data', exist_ok=True)
out = '../data/china_age_consumption.csv'
with open(out, 'w', encoding='utf-8-sig', newline='') as f:
    w = csv.writer(f)
    w.writerow(['evidence_level', 'source_id', 'source_name', 'year', 'geography', 'sample',
                'age_band', 'life_stage', 'category', 'value_yuan', 'share_pct', 'unit_note'])
    w.writerows(rows)
print('rows', len(rows), '->', out)
